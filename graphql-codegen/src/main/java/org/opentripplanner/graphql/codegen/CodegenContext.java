package org.opentripplanner.graphql.codegen;

import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.ParameterizedTypeName;
import com.palantir.javapoet.TypeName;
import com.palantir.javapoet.TypeSpec;
import graphql.language.Description;
import graphql.language.ListType;
import graphql.language.NonNullType;
import graphql.language.Type;
import graphql.language.TypeDefinition;
import graphql.schema.idl.TypeDefinitionRegistry;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import javax.lang.model.SourceVersion;
import org.opentripplanner.graphql.codegen.CodegenConfig.OutputFile;

/**
 * The parsed schema together with the configuration of a single output file. Holds the naming and
 * type mapping rules shared by the generators.
 */
final class CodegenContext {

  private static final Map<String, String> BUILT_IN_SCALARS = Map.of(
    "ID",
    "Object",
    "String",
    "String",
    "Boolean",
    "Boolean",
    "Int",
    "Integer",
    "Float",
    "Double"
  );

  private static final String DEFAULT_TYPE = "Object";
  private static final String HEADER =
    "THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.";

  private final TypeDefinitionRegistry registry;
  private final OutputFile output;
  private final JavaTypeParser typeParser;

  CodegenContext(TypeDefinitionRegistry registry, OutputFile output, JavaTypeParser typeParser) {
    this.registry = registry;
    this.output = output;
    this.typeParser = typeParser;
  }

  OutputFile output() {
    return output;
  }

  ClassName outerClass() {
    return ClassName.get(output.packageName(), output.className());
  }

  /** All type definitions of the schema. */
  Collection<TypeDefinition> types() {
    return registry.types().values();
  }

  TypeDefinition<?> typeDefinition(String name) {
    return registry.getTypeOrNull(name);
  }

  /** The name of a generated type: the configured prefix followed by the capitalized name. */
  String javaTypeName(String graphQLName) {
    return output.typesPrefix() + capitalize(graphQLName);
  }

  static String capitalize(String name) {
    return Character.toUpperCase(name.charAt(0)) + name.substring(1);
  }

  /** The Java name of a field, prefixed with an underscore if it is a reserved word. */
  static String javaMemberName(String graphQLName) {
    return SourceVersion.isKeyword(graphQLName) ? "_" + graphQLName : graphQLName;
  }

  boolean isScalar(String graphQLName) {
    return BUILT_IN_SCALARS.containsKey(graphQLName) || registry.scalars().containsKey(graphQLName);
  }

  /** The Java type of a scalar. Scalars without a configured type are mapped to {@code Object}. */
  TypeName scalarType(String graphQLName) {
    String javaType = output.scalars().get(graphQLName);
    if (javaType == null) {
      javaType = BUILT_IN_SCALARS.getOrDefault(graphQLName, DEFAULT_TYPE);
    }
    return typeParser.parse(javaType);
  }

  TypeName parseType(String javaType) {
    return typeParser.parse(javaType);
  }

  TypeName defaultType() {
    return typeParser.parse(DEFAULT_TYPE);
  }

  ClassName listType() {
    return switch (output.listType()) {
      case "List" -> ClassName.get(List.class);
      case "Iterable" -> ClassName.get(Iterable.class);
      default -> typeParser.resolveName(output.listType());
    };
  }

  /** Wraps {@code baseType} in the configured list type for each list level of {@code type}. */
  TypeName wrapWithLists(TypeName baseType, Type<?> type) {
    if (type instanceof NonNullType nonNull) {
      return wrapWithLists(baseType, nonNull.getType());
    }
    if (type instanceof ListType list) {
      return ParameterizedTypeName.get(listType(), wrapWithLists(baseType, list.getType()));
    }
    return baseType;
  }

  static int listDepth(Type<?> type) {
    if (type instanceof NonNullType nonNull) {
      return listDepth(nonNull.getType());
    }
    if (type instanceof ListType list) {
      return 1 + listDepth(list.getType());
    }
    return 0;
  }

  static String baseTypeName(Type<?> type) {
    if (type instanceof NonNullType nonNull) {
      return baseTypeName(nonNull.getType());
    }
    if (type instanceof ListType list) {
      return baseTypeName(list.getType());
    }
    return ((graphql.language.TypeName) type).getName();
  }

  /** Adds the GraphQL description as JavaDoc, if there is one. */
  static void addJavadoc(TypeSpec.Builder builder, Description description) {
    if (description == null || description.getContent() == null) {
      return;
    }
    String content = description.getContent().strip();
    if (!content.isEmpty()) {
      builder.addJavadoc("$L\n", content.replace("*/", "*\\/"));
    }
  }

  JavaFile toJavaFile(TypeSpec type) {
    return JavaFile.builder(output.packageName(), type).addFileComment(HEADER).build();
  }
}
