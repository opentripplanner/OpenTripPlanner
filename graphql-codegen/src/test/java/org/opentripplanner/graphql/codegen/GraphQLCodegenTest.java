package org.opentripplanner.graphql.codegen;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class GraphQLCodegenTest {

  @TempDir
  static Path outputDir;

  private static String types;
  private static String dataFetchers;

  @BeforeAll
  static void generate() throws IOException, URISyntaxException {
    var config = Path.of(GraphQLCodegenTest.class.getResource("codegen.yml").toURI());
    GraphQLCodegen.generate(config, outputDir);
    types = read("TestTypes.java");
    dataFetchers = read("TestDataFetchers.java");
  }

  @Test
  void headerAndPackage() {
    assertTrue(
      types.startsWith(
        "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY. package org.example.generated;"
      )
    );
  }

  @Test
  void enumKeepsSchemaOrder() {
    assertContains(types, "public enum GraphQLMode { BUS, CABLE_CAR }");
  }

  @Test
  void inputObjectGetsInputSuffixOnlyWhenMissing() {
    assertContains(types, "public static class GraphQLFilterInput {");
    assertContains(types, "public static class GraphQLNestedInput {");
  }

  @Test
  void listOfEnumsIsMappedFromStrings() {
    assertContains(types, "private final List<GraphQLMode> modes;");
    assertContains(types, "GraphQLMode.valueOf((String) item)");
  }

  @Test
  void argsClassForFieldWithArguments() {
    assertContains(types, "public static class GraphQLStopRoutesArgs {");
    assertContains(
      types,
      "this.filter = new GraphQLFilterInput((Map<String, Object>) args.get(\"filter\"));"
    );
    assertContains(types, "public Integer getGraphQLFirst() {");
    assertFalse(types.contains("setGraphQL"));
  }

  @Test
  void customScalarMapping() {
    assertContains(types, "private final Relay.ResolvedGlobalId id;");
  }

  @Test
  void objectTypeDataFetchersUseMappers() {
    assertContains(dataFetchers, "import org.example.model.StopModel;");
    assertContains(dataFetchers, "DataFetcher<StopModel> stop();");
    assertContains(dataFetchers, "DataFetcher<TransitMode> mode();");
    assertContains(dataFetchers, "DataFetcher<Iterable<Route>> routes();");
  }

  @Test
  void unmappedAbstractTypeIsObject() {
    assertContains(dataFetchers, "DataFetcher<Object> node();");
  }

  @Test
  void descriptionIsJavadoc() {
    assertContains(dataFetchers, "/** * A stop */ public interface GraphQLStop {");
  }

  @Test
  void noInterfacesForInterfaceAndUnionTypes() {
    assertFalse(dataFetchers.contains("GraphQLNode "));
    assertFalse(dataFetchers.contains("GraphQLStopOrStation "));
    assertFalse(dataFetchers.contains("TypeResolver"));
  }

  @Test
  void unchangedFileIsNotRewritten() throws IOException, URISyntaxException {
    var file = outputDir.resolve("org/example/generated/TestTypes.java");
    var modified = FileTime.fromMillis(0);
    Files.setLastModifiedTime(file, modified);
    var config = Path.of(GraphQLCodegenTest.class.getResource("codegen.yml").toURI());
    GraphQLCodegen.generate(config, outputDir);
    assertEquals(modified, Files.getLastModifiedTime(file));
  }

  private static void assertContains(String actual, String expected) {
    assertTrue(actual.contains(expected), () -> "Expected to find:\n" + expected);
  }

  /** Reads a generated file with all whitespace collapsed, so assertions ignore formatting. */
  private static String read(String fileName) throws IOException {
    return Files.readString(
      outputDir.resolve("org/example/generated").resolve(fileName),
      StandardCharsets.UTF_8
    ).replaceAll("\\s+", " ");
  }
}
